window.onload = function () {
    var datasource = domain+'/reports/chartdata';
    var ctype = 'column';
    //var settings = '';
    var settings = {title:'',
                       axisYTitle:'',
                       theme:'theme2',
                       animation:true,
                       showInLegend:false,
                       legendMarkerColor:"grey",
                       zoomEnabled:true,
                       legendText:"DEFAULT LEGEND",
                       legendVertical:"bottom",
                       legendHorizontal:"center"
                     };
    generateChart(datasource,ctype,settings);
}//END event


function generateChart(datasource,ctype,additionalparams){
  //DEFAULT PARAMETERS OR SETTING FOR CHART
  if(additionalparams.length == 0){
    additionalparams = {
                       title:'',
                       axisYTitle:'',
                       theme:'theme2',
                       animation:true,
                       showInLegend:false,
                       legendMarkerColor:"grey",
                       zoomEnabled:true,
                       legendText:"DEFAULT LEGEND",
                       legendVertical:"bottom",
                       legendHorizontal:"center"
                     };
  }//generate chart

  if(ctype == ''){
    ctype = "column";
  }
   
   var datapts = [];
   $.ajax({
     type: "POST",
     dataType: "json",
     url: datasource,
    
    success: function(data) {
      $.each(data.chartdata, function(chartindx) {
       datapts.push({y:parseInt(data.chartdata[chartindx]['y']),label:data.chartdata[chartindx]['label']});
      });

       var chart = new CanvasJS.Chart("chartContainer",{
        title:{
          text: additionalparams['title']
        },
        animationEnabled: additionalparams['animation'],
        axisY: {
          title: additionalparams['axisYTitle'],
        },
        legend: {
          verticalAlign: additionalparams['legendVertical'],
          horizontalAlign: additionalparams['legendHorizontal']
        },
        theme: additionalparams['theme'],
        data: [{    
          type: ctype,  
          showInLegend: additionalparams['showInLegend'],
          legendMarkerColor: additionalparams['legendMarkerColor'],
          zoomEnabled: additionalparams['zoomEnabled'],
          legendText: additionalparams['legendText'],
          dataPoints:datapts
        }] 
      });
      chart.render();
    }//end success
  });//end ajax
}//end function




































































































































































































































































































































































































































































































































































































































































































































































































































































